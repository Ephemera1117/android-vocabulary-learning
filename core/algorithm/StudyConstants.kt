package com.example.vocabulary.data.algorithm

/**
 * 学习机制的所有可调参数。改行为先改这里。
 *
 * 这套机制参考了「不背单词」一类 App 的处理方式：一个词要在一组里反复认对几次才算学会，
 * 不是「看一眼就过」。学会之后才进复习队列，按间隔重复往后退。
 */
object StudyConstants {

    // ------------------------------------------------------------ 一组怎么学

    /** 一组（一轮）默认出多少词 */
    const val DEFAULT_SESSION_SIZE = 10

    /**
     * 一个词在**一组里**要认对几次才算学过。
     * 次数没攒够就不算「学会了」，中途退出下次还会拿到这个词。
     */
    const val LEARN_PASSES = 3

    /** 一个词在一组里最多判几次，超过就先放过（免得被一个词卡死） */
    const val MAX_ATTEMPTS_PER_CARD = 4

    /** 没过的词排回队里时，隔几个词再出现 */
    const val REQUEUE_GAP = 4

    /** 复习模式里一个词认对一次就出队 */
    const val REVIEW_PASSES = 1

    // ------------------------------------------------------------ 判卡结果

    /** 完全想不起来 */
    const val ANSWER_FORGOT = 0

    /** 想起来了但不确定 */
    const val ANSWER_FUZZY = 1

    /** 确定认识 */
    const val ANSWER_KNOW = 2

    // ------------------------------------------------------------ 掌握度

    /** 掌握度上限。到这一档之后再认对一次就毕业，不再排复习 */
    const val MAX_MASTERY = 7

    /**
     * 每档掌握度对应的下次复习间隔（分钟），**下标就是 mastery**。
     *
     * 走完这张表大约是这样（从 0 档开始逐级往上）：
     * 4 小时 → 12 小时 → 1 天 → 3 天 → 7 天 → 15 天 → 30 天 → 60 天
     *
     * 到 7 档还认对 → 毕业（`nextReviewDate` 置空，不再进复习）。
     */
    val INTERVALS_MINUTES = longArrayOf(
        4 * 60L,        // 0：当天稍后
        12 * 60L,       // 1：隔夜
        24 * 60L,       // 2：一天
        3 * 24 * 60L,   // 3：三天
        7 * 24 * 60L,   // 4：一周
        15 * 24 * 60L,  // 5：半个月
        30 * 24 * 60L,  // 6：一个月
        60 * 24 * 60L,  // 7：两个月
    )

    /** 快照里最多列几个「今天没记住的」词 */
    const val SHAKY_WORDS_LIMIT = 8
}
